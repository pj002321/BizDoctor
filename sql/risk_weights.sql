-- ===================================================================
-- 상권 신호등 — 지역 및 업종별 연체(폐업) 위험 가중치 산출
--
-- preprocess_seoul_panel.py 의 pandas 전처리를 SQL로 옮긴 것.
-- 윈도우 함수로 시계열 피처(다음분기 타겟, 변화량, 이동평균)와
-- 업종 내 상대 위험순위를 한 번의 스캔으로 만든다.
--
-- 실행: python run_sql_analysis.py
-- ===================================================================

-- -------------------------------------------------------------------
-- [1] 피처 생성 — 패널에 업종 대분류를 붙이고 시계열 피처를 계산
-- -------------------------------------------------------------------
WITH panel AS (
    SELECT p.*, d."KOSIS_산업1"
    FROM seoul_panel p
    LEFT JOIN dim_industry d
           ON p."서비스_업종_코드_명" = d."서비스_업종_코드_명"
),
featured AS (
    SELECT
        "기준_년분기_코드",
        "행정동_코드", "행정동_코드_명",
        "서비스_업종_코드", "서비스_업종_코드_명", "KOSIS_산업1",
        "점포_수", "폐업_률", "개업_율", "폐업_점포_수", "프랜차이즈_점포_수",

        -- 타겟: 같은 (행정동, 업종) 셀의 다음 분기 폐업률
        LEAD("폐업_률") OVER w_cell                       AS "다음분기_폐업률",

        -- 추세: 직전 분기 대비 변화량
        "폐업_률" - LAG("폐업_률") OVER w_cell             AS "폐업률_변화",

        -- 노이즈 완화: 최근 2개 분기 이동평균
        AVG("폐업_률") OVER (
            PARTITION BY "행정동_코드", "서비스_업종_코드"
            ORDER BY "기준_년분기_코드"
            ROWS BETWEEN 1 PRECEDING AND CURRENT ROW
        )                                                 AS "폐업률_2분기평균",

        -- 위축 국면 신호: 양수면 폐업이 개업을 앞지름
        "폐업_률" - "개업_율"                              AS "폐업개업_격차",

        CASE WHEN "점포_수" > 0
             THEN 1.0 * "프랜차이즈_점포_수" / "점포_수"
        END                                               AS "프랜차이즈_비중",

        -- ★ 핵심: 같은 분기·같은 업종 안에서의 상대 위험순위(0~1)
        --
        --   SQL 표준의 PERCENT_RANK()/CUME_DIST()는 동점 처리 방식이
        --   pandas 의 rank(pct=True, method='average') 와 다르다.
        --   폐업률은 76%가 0이라 동점이 지배적이므로, 평균순위를 직접 만든다:
        --
        --     평균순위 = 최소순위 + (동점개수 - 1) / 2
        --     percentile = 평균순위 / 파티션 행수
        --
        (CAST(RANK() OVER w_rank AS REAL)
            + (COUNT(*) OVER w_tie - 1) / 2.0)
        / COUNT(*) OVER w_part                            AS "폐업률_업종내_percentile"

    FROM panel
    WINDOW
        w_cell AS (PARTITION BY "행정동_코드", "서비스_업종_코드"
                   ORDER BY "기준_년분기_코드"),
        w_rank AS (PARTITION BY "기준_년분기_코드", "서비스_업종_코드"
                   ORDER BY "폐업_률"),
        w_tie  AS (PARTITION BY "기준_년분기_코드", "서비스_업종_코드", "폐업_률"),
        w_part AS (PARTITION BY "기준_년분기_코드", "서비스_업종_코드")
)
-- 타겟이 없는 마지막 분기 행은 학습에 쓸 수 없으므로 제외
SELECT *
FROM featured
WHERE "다음분기_폐업률" IS NOT NULL;


