# -*- coding: utf-8 -*-
"""
상권 신호등 - 서울 폐업률 패널데이터 전처리 스크립트

핵심 설계 변경사항:
- 기존: Kaggle 해외 개인신용데이터를 소상공인 프록시로 사용 (국적 불일치로 폐기)
- 변경: 서울시 상권분석서비스(점포-행정동) 실데이터를 그대로 학습 데이터로 사용
- 학습 단위: 개인이 아니라 "행정동 x 서비스업종" 조합 (패널데이터)
- 타겟: 다음 분기 폐업_률 (실제 값, 라벨링/프록시 불필요)
"""
import pandas as pd
import numpy as np
import os
import sys
from pathlib import Path

# ai-service/ 를 import 경로에 넣어 app/core/config.py 를 쓴다(이 줄은 config 를 찾기 위한 것).
# 입출력 경로는 config.DATA_DIR(ai-service/data) 한 곳에서 정한다. 어디서 실행해도 같은 파일을 읽고 쓴다.
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from app.core import config  # noqa: E402

os.chdir(config.DATA_DIR)

# ------------------------------------------------------------------
# 1. 서울 점포-행정동 패널데이터 로드 (2023~2025, 3개년 12개 분기)
# ------------------------------------------------------------------
df = pd.read_parquet("seoul_panel_raw.parquet")

# 분기 코드(20231 등)를 정렬 가능한 순번으로 변환
df = df.sort_values(["행정동_코드", "서비스_업종_코드", "기준_년분기_코드"]).reset_index(drop=True)

# ------------------------------------------------------------------
# 2. 서비스업종(100개) → KOSIS 산업중분류(12개) 매핑
#    (KOSIS 애로사항 데이터와 조인하기 위한 근사 매핑. 필요시 세부 조정)
# ------------------------------------------------------------------
INDUSTRY_MAP = {
    # 숙박 및 음식점업
    **{k: "숙박 및 음식점업" for k in [
        "한식음식점","중식음식점","일식음식점","양식음식점","제과점","패스트푸드점",
        "치킨전문점","분식전문점","호프-간이주점","커피-음료","여관","게스트하우스","고시원"]},
    # 도매 및 소매업
    **{k: "도매 및 소매업" for k in [
        "가구","가방","가전제품","문구","미곡판매","반찬가게","서적","섬유제품","수산물판매",
        "슈퍼마켓","시계및귀금속","신발","악기","안경","애완동물","완구","운동/경기용품",
        "유아의류","육류판매","의료기기","의약품","일반의류","자동차부품","재생용품 판매점",
        "조명용품","주류도매","중고가구","중고차판매","철물점","청과상","컴퓨터및주변장치판매",
        "편의점","핸드폰","화장품","화초","한복점","예술품","자전거 및 기타운송장비",
        "모터사이클및부품","주유소","전자상거래업"]},
    # 예술, 스포츠 및 여가관련 서비스업
    **{k: "예술, 스포츠 및 여가관련 서비스업" for k in [
        "골프연습장","당구장","볼링장","스포츠클럽","스포츠 강습","노래방","DVD방","PC방",
        "기타오락장","복권방","녹음실","예술학원","전자게임장"]},
    # 협회 및 단체, 수리 및 기타 개인서비스업
    **{k: "협회 및 단체, 수리 및 기타 개인서비스업" for k in [
        "미용실","네일숍","피부관리실","세탁소","가전제품수리","자동차수리","자동차미용",
        "통신기기수리","모터사이클수리","사진관"]},
    "미용재료": "도매 및 소매업",
    # 교육 서비스업
    **{k: "교육 서비스업" for k in [
        "일반교습학원","외국어학원","컴퓨터학원","독서실"]},
    # 전문과학기술서비스업
    **{k: "전문과학기술서비스업" for k in [
        "법무사사무소","변리사사무소","변호사사무소","세무사사무소","회계사사무소",
        "기타법무서비스","통번역서비스"]},
    # 부동산업
    **{k: "부동산업" for k in ["부동산중개업"]},
    # 사업시설관리, 사업지원 및 임대 서비스업
    **{k: "사업시설관리, 사업지원 및 임대 서비스업" for k in [
        "여행사","건축물청소","가정용품임대","비디오/서적임대","의류임대","인테리어"]},
    # 보건업으로 별도 분류가 KOSIS 표에 없어 "협회 및 단체..." 로 임시 배치 (필요시 조정)
    **{k: "협회 및 단체, 수리 및 기타 개인서비스업" for k in ["일반의원","치과의원","한의원","동물병원"]},
}
df["KOSIS_산업1"] = df["서비스_업종_코드_명"].map(INDUSTRY_MAP)
unmapped = df.loc[df["KOSIS_산업1"].isna(), "서비스_업종_코드_명"].unique()
if len(unmapped) > 0:
    print("[경고] 매핑 안 된 업종 (수동 확인 필요):", unmapped)

# ------------------------------------------------------------------
# 3. 타겟 생성: 다음 분기 폐업_률 (행정동 x 업종 그룹 내에서 shift)
# ------------------------------------------------------------------
df["다음분기_폐업률"] = df.groupby(["행정동_코드", "서비스_업종_코드"])["폐업_률"].shift(-1)

# ------------------------------------------------------------------
# 4. 피처 엔지니어링
# ------------------------------------------------------------------
grp = df.groupby(["행정동_코드", "서비스_업종_코드"])

# (a) 추세 피처: 직전 분기 대비 폐업률 변화량
df["폐업률_변화"] = grp["폐업_률"].diff()

# (b) 이동평균: 최근 2개 분기 평균 폐업률 (노이즈 완화)
df["폐업률_2분기평균"] = grp["폐업_률"].transform(lambda s: s.rolling(2, min_periods=1).mean())

# (c) 업종 내 상대순위 (같은 분기, 같은 업종 안에서 percentile) — 절대값 대신 상대 위험도
df["폐업률_업종내_percentile"] = df.groupby(["기준_년분기_코드", "서비스_업종_코드"])["폐업_률"] \
    .rank(pct=True)

# (d) 개업률 대비 폐업률 격차 (양수면 위축 국면)
df["폐업개업_격차"] = df["폐업_률"] - df["개업_율"]

# (e) 프랜차이즈 비중 (동일업종 경쟁 심화 신호로 활용 가능)
#   서울시 원본에서 점포_수 = 프랜차이즈를 뺀 일반 점포, 유사_업종_점포_수 = 일반 + 프랜차이즈(전체).
#   (387,266행 전부 유사_업종_점포_수 == 점포_수 + 프랜차이즈_점포_수, 폐업_률도 유사_업종_점포_수가 분모)
#   점포_수로 나누면 비중이 1을 넘는다(최대 23). 전체 점포로 나눠 0~1 로 맞춘다.
df["프랜차이즈_비중"] = np.where(
    df["유사_업종_점포_수"] > 0, df["프랜차이즈_점포_수"] / df["유사_업종_점포_수"], np.nan
)

# ------------------------------------------------------------------
# 5. 학습 가능한 행만 필터링 (타겟 없는 마지막 분기 행 제외)
# ------------------------------------------------------------------
model_df = df.dropna(subset=["다음분기_폐업률"]).copy()

print("전체 패널:", df.shape)
print("모델 학습용(타겟 존재):", model_df.shape)
print()
print("타겟(다음분기_폐업률) 분포:")
print(model_df["다음분기_폐업률"].describe())

# ------------------------------------------------------------------
# 6. 저장
# ------------------------------------------------------------------
model_df.to_csv("seoul_panel_model_ready.csv", index=False, encoding="utf-8-sig")
print("\n저장 완료: seoul_panel_model_ready.csv")
print(model_df[[
    "기준_년분기_코드","행정동_코드_명","서비스_업종_코드_명","KOSIS_산업1",
    "폐업_률","다음분기_폐업률","폐업률_변화","폐업률_2분기평균",
    "폐업률_업종내_percentile","폐업개업_격차","프랜차이즈_비중"
]].head(10).to_string())